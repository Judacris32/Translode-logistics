// Turns data/demo.json into supabase/seed.sql, so the sample shipments in the
// database are the same ones the site shows before Supabase is connected.
// Run with: npm run seed:build
import { readFileSync, writeFileSync } from "node:fs";

const demo = JSON.parse(readFileSync(new URL("../data/demo.json", import.meta.url), "utf8"));

const q = (v) => (v === null || v === undefined ? "null" : `'${String(v).replace(/'/g, "''")}'`);
const ago = (hours) => `now() - interval '${Math.round(hours * 60)} minutes'`;
const ahead = (hours) =>
  hours >= 0 ? `now() + interval '${Math.round(hours * 60)} minutes'` : ago(-hours);

const out = [];
out.push("-- Sample data for Translode Logistics. Generated by scripts/build-seed.mjs from data/demo.json.");
out.push("-- Do not edit by hand. Safe to run more than once: it replaces the sample rows.");
out.push("-- Times are relative to the moment you run it, so the shipments always look current.");
out.push("");
out.push("begin;");
out.push("");
out.push("insert into public.hubs (code, name, city, state, kind, lat, lng) values");
out.push(
  demo.hubs
    .map((h) => `  (${q(h.code)}, ${q(h.name)}, ${q(h.city)}, ${q(h.state)}, ${q(h.kind)}, ${h.lat}, ${h.lng})`)
    .join(",\n"),
);
out.push("on conflict (code) do update set");
out.push("  name = excluded.name, city = excluded.city, state = excluded.state,");
out.push("  kind = excluded.kind, lat = excluded.lat, lng = excluded.lng;");
out.push("");
out.push("delete from public.shipments where tracking_number in (");
out.push(demo.shipments.map((s) => `  ${q(s.trackingNumber)}`).join(",\n"));
out.push(");");
out.push("");

for (const s of demo.shipments) {
  const events = [...s.events].sort((a, b) => b.hoursAgo - a.hoursAgo); // oldest first
  const truck = s.service === "haulage" ? (s.weightGrams > 15_000_000 ? "30t" : s.weightGrams > 5_000_000 ? "15t" : "5t") : null;

  out.push(`-- ${s.trackingNumber}: ${s.originCity} to ${s.destinationCity}`);
  out.push("insert into public.shipments (");
  out.push("  tracking_number, service, sender_name, sender_phone, origin_city, origin_address,");
  out.push("  receiver_name, receiver_phone, destination_city, destination_address, destination_country,");
  out.push("  description, pieces, weight_grams, truck_size, declared_value_kobo, price_kobo, paid,");
  out.push("  eta, signed_by, created_at");
  out.push(") values (");
  out.push(`  ${q(s.trackingNumber)}, ${q(s.service)}, ${q(s.senderName)}, ${q(s.senderPhone)}, ${q(s.originCity)}, ${q(s.originAddress)},`);
  out.push(`  ${q(s.receiverName)}, ${q(s.receiverPhone)}, ${q(s.destinationCity)}, ${q(s.destinationAddress)}, ${q(s.destinationCountry)},`);
  out.push(`  ${q(s.description)}, ${s.pieces}, ${s.weightGrams}, ${q(truck)}, ${s.declaredValueKobo}, ${s.priceKobo}, ${s.paid},`);
  out.push(`  ${ahead(s.etaHours)}, ${q(s.signedBy)}, ${ago(events[0].hoursAgo)}`);
  out.push(");");
  out.push("insert into public.tracking_events (shipment_id, status, hub_id, location, note, occurred_at)");
  out.push("select s.id, e.status::public.shipment_status, h.id, e.location, e.note, e.occurred_at");
  out.push("from public.shipments s");
  out.push("cross join (values");
  out.push(
    events
      .map((e) => `  (${q(e.status)}, ${q(e.hub)}, ${q(e.location)}, ${q(e.note)}, ${ago(e.hoursAgo)})`)
      .join(",\n"),
  );
  out.push(") as e (status, hub_code, location, note, occurred_at)");
  out.push("left join public.hubs h on h.code = e.hub_code");
  out.push(`where s.tracking_number = ${q(s.trackingNumber)}`);
  out.push("order by e.occurred_at;");
  out.push("");
}

out.push("commit;");
out.push("");

writeFileSync(new URL("../supabase/seed.sql", import.meta.url), out.join("\n"));
console.log(`Wrote supabase/seed.sql with ${demo.hubs.length} hubs and ${demo.shipments.length} shipments.`);
